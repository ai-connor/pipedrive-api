// RoundTrip implements http.RoundTripper. On a retryable (by default 429)
// response it waits using exponential backoff with full jitter (or the
// Retry-After header, when present and enabled) and retries, up to MaxRetries.
// The wait always respects the request context's deadline/cancellation.
func (t *rateLimitTransport) RoundTrip(req *http.Request) (*http.Response, error) {
	base := t.base
	if base == nil {
		base = http.DefaultTransport
	}

	// A request body can only be replayed if GetBody is available. When it is
	// not, fall back to a single attempt rather than risk sending a consumed or
	// partial body. The generated client builds bodies from *bytes.Buffer, so
	// net/http populates GetBody automatically for all generated requests.
	if req.Body != nil && req.Body != http.NoBody && req.GetBody == nil {
		return base.RoundTrip(req)
	}

	ctx := req.Context()

	for attempt := 0; ; attempt++ {
		// Operate on a clone each attempt so the caller's request is never
		// mutated, honouring the RoundTripper contract.
		attemptReq := req.Clone(ctx)
		if req.GetBody != nil {
			body, err := req.GetBody()
			if err != nil {
				return nil, err
			}
			attemptReq.Body = body
		}

		resp, err := base.RoundTrip(attemptReq)
		if err != nil {
			// Transport-level errors (timeouts, connection failures) are outside
			// the scope of the 429 handler; surface them to the caller.
			return resp, err
		}

		if attempt >= t.cfg.MaxRetries || !t.isRetryable(resp.StatusCode) {
			return resp, nil
		}

		delay := t.backoff(attempt, resp)

		if t.cfg.OnRetry != nil {
			t.cfg.OnRetry(attempt, delay, resp)
		}

		// The response is being discarded; drain a bounded amount and close it so
		// the underlying connection can be reused for the retry.
		drainAndClose(resp.Body)

		timer := time.NewTimer(delay)
		select {
		case <-ctx.Done():
			timer.Stop()
			return nil, ctx.Err()
		case <-timer.C:
		}
	}
}

// isRetryable reports whether a status code is configured to trigger a retry.
func (t *rateLimitTransport) isRetryable(status int) bool {
	for _, code := range t.cfg.RetryableStatusCodes {
		if status == code {
			return true
		}
	}
	return false
}

// backoff computes the wait before the next retry. When enabled and present, a
// Retry-After header takes precedence; otherwise it uses exponential backoff
// with full jitter. The result is always bounded by MaxDelay.
func (t *rateLimitTransport) backoff(attempt int, resp *http.Response) time.Duration {
	if t.cfg.RespectRetryAfter && resp != nil {
		if d, ok := parseRetryAfter(resp.Header.Get("Retry-After")); ok {
			if d > t.cfg.MaxDelay {
				d = t.cfg.MaxDelay
			}
			return d
		}
	}

	// Exponential backoff: BaseDelay * 2^attempt, capped at MaxDelay, computed in
	// float to avoid integer overflow on large attempt counts.
	backoff := float64(t.cfg.BaseDelay) * math.Pow(2, float64(attempt))
	if capped := float64(t.cfg.MaxDelay); backoff > capped {
		backoff = capped
	}

	// Full jitter: sleep a random duration in [0, backoff]. This spreads
	// concurrent clients out and avoids synchronised retry storms.
	return time.Duration(rand.Int64N(int64(backoff) + 1))
}

// parseRetryAfter interprets a Retry-After header value, which may be either a
// non-negative integer number of seconds or an HTTP date. It returns the delay
// and whether parsing succeeded.
func parseRetryAfter(v string) (time.Duration, bool) {
	v = strings.TrimSpace(v)
	if v == "" {
		return 0, false
	}

	if secs, err := strconv.Atoi(v); err == nil {
		if secs < 0 {
			return 0, false
		}
		return time.Duration(secs) * time.Second, true
	}

	if when, err := http.ParseTime(v); err == nil {
		d := time.Until(when)
		if d < 0 {
			d = 0
		}
		return d, true
	}

	return 0, false
}

// drainAndClose discards a bounded amount of the response body and closes it,
// allowing the underlying TCP connection to be reused.
func drainAndClose(body io.ReadCloser) {
	if body == nil {
		return
	}
	_, _ = io.Copy(io.Discard, io.LimitReader(body, 4096))
	_ = body.Close()
}
